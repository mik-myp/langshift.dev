def test_autogenerate_detects_column_drift_not_a_data_audit(database_url, engine):
    upgrade(database_url)
    with engine.begin() as connection:
        connection.execute(text("ALTER TABLE tasks ADD COLUMN accidental text"))
    with pytest.raises(AutogenerateDiffsDetected):
        command.check(configuration(database_url))


def test_head_rejects_invalid_priority(database_url, engine):
    upgrade(database_url)
    with engine.begin() as connection:
        _, _, task = insert_old_task(connection)
    for value in (None, -1, 3):
        with pytest.raises(IntegrityError):
            with engine.begin() as connection:
                connection.execute(text("UPDATE tasks SET priority=:v WHERE id=:id"), {"v": value, "id": task})
    with engine.connect() as connection:
        assert connection.scalar(text("SELECT priority FROM tasks")) == 0

def test_autogenerate_rename_candidate_requires_human_review(database_url, engine, tmp_path):
    import shutil
    from pathlib import Path
    upgrade(database_url)
    with engine.begin() as connection:
        insert_old_task(connection)
        connection.execute(text("ALTER TABLE tasks RENAME COLUMN description TO note"))
    # Generate into a scratch script directory, never edit the shipped history.
    scripts = tmp_path / "migrations"
    shutil.copytree(Path(__file__).resolve().parents[1] / "migrations", scripts,
                    ignore=shutil.ignore_patterns("__pycache__"))
    config = configuration(database_url)
    config.set_main_option("script_location", str(scripts))
    candidate = command.revision(config, message="review rename candidate", autogenerate=True)
    source = Path(candidate.path).read_text()
    assert "op.add_column" in source and "op.drop_column" in source
    assert "description" in source and "note" in source
    with engine.connect() as connection:
        assert connection.scalar(text("SELECT note FROM tasks")) == "keep this note"
        assert connection.scalar(text("SELECT version_num FROM alembic_version")) == "003_contract"
