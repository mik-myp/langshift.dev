from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
import pytest
from sqlalchemy import inspect, text
from sqlalchemy.exc import IntegrityError
from history_data import insert_old_task, snapshot
from migrate import configuration, upgrade
from db import make_engine


@pytest.fixture
def engine(database_url):
    engine = make_engine(database_url)
    try:
        yield engine
    finally:
        outstanding = engine.pool.checkedout()
        engine.dispose()
        assert outstanding == 0


def test_empty_database_upgrades_to_head(database_url, engine):
    upgrade(database_url)
    assert set(inspect(engine).get_table_names()) == {"users", "projects", "project_members", "tasks", "alembic_version"}
    with engine.connect() as connection:
        assert connection.scalar(text("SELECT version_num FROM alembic_version")) == "003_contract"
    command.check(configuration(database_url))


def test_existing_rows_preserved_and_old_writer_still_works(database_url, engine):
    upgrade(database_url, "001_base")
    with engine.begin() as connection:
        user, project, first = insert_old_task(connection)
    upgrade(database_url, "002_expand")
    with engine.begin() as connection:
        insert_old_task(connection, "During expansion", user_id=user, project_id=project)
        before = snapshot(connection)
        connection.execute(text("UPDATE tasks SET priority=2 WHERE id=:id"), {"id": first})
    upgrade(database_url)
    with engine.begin() as connection:
        assert snapshot(connection) == before
        assert list(connection.execute(text("SELECT priority FROM tasks ORDER BY id")).scalars()) == [2, 0]
        _, _, last = insert_old_task(connection, "After contract", user_id=user, project_id=project)
        assert connection.scalar(text("SELECT priority FROM tasks WHERE id=:id"), {"id": last}) == 0


def test_invalid_existing_data_rolls_back_entire_migration(database_url, engine):
    upgrade(database_url, "002_expand")
    with engine.begin() as connection:
        user, project, bad = insert_old_task(connection)
        insert_old_task(connection, "Still NULL", user_id=user, project_id=project)
        connection.execute(text("UPDATE tasks SET priority=9 WHERE id=:id"), {"id": bad})
    with pytest.raises(IntegrityError):
        upgrade(database_url)
    with engine.connect() as connection:
        assert connection.scalar(text("SELECT version_num FROM alembic_version")) == "002_expand"
        assert list(connection.execute(text("SELECT priority FROM tasks ORDER BY id")).scalars()) == [9, None]
    columns = {column["name"]: column for column in inspect(engine).get_columns("tasks")}
    assert columns["priority"]["nullable"] is True
    assert columns["priority"]["default"] is None
    with engine.begin() as connection:
        connection.execute(text("UPDATE tasks SET priority=2 WHERE priority=9"))
    upgrade(database_url)
    command.check(configuration(database_url))


def test_data_losing_downgrade_is_refused(database_url, engine):
    upgrade(database_url)
    with engine.begin() as connection:
        insert_old_task(connection)
        before = snapshot(connection)
    with pytest.raises(RuntimeError, match="Refusing"):
        command.downgrade(configuration(database_url), "001_base")
    with engine.connect() as connection:
        assert snapshot(connection) == before
        assert connection.scalar(text("SELECT version_num FROM alembic_version")) == "003_contract"
    command.check(configuration(database_url))


